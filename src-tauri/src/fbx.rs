use std::{
    fs::{self, File},
    io::{BufWriter, Write},
    path::Path,
};

const VISUAL_GEOMETRY_ID: i64 = 1_001_001;
const VISUAL_MODEL_ID: i64 = 1_001_002;
const VISUAL_MATERIAL_ID: i64 = 1_001_003;
const COLLIDER_GEOMETRY_ID: i64 = 1_002_001;
const COLLIDER_MODEL_ID: i64 = 1_002_002;

#[derive(Debug, Clone, Copy)]
pub struct FbxVertex {
    pub position: [f64; 3],
    pub color: [f64; 4],
}

pub struct FbxMesh<'a> {
    pub name: &'a str,
    pub vertices: &'a [FbxVertex],
    /// Zero-based triangle vertex indices.
    pub triangles: &'a [[u32; 3]],
}

pub fn write_fbx(path: &Path, visual: FbxMesh<'_>, collider: FbxMesh<'_>) -> Result<(), String> {
    validate_mesh(&visual)?;
    validate_mesh(&collider)?;

    let file = File::create(path)
        .map_err(|error| format!("failed to create native FBX {}: {error}", path.display()))?;
    let mut writer = BufWriter::new(file);
    write_header(&mut writer)?;
    write_definitions(&mut writer)?;

    writeln!(writer, "Objects: {{").map_err(io_error)?;
    write_geometry(&mut writer, VISUAL_GEOMETRY_ID, visual.name, &visual, true)?;
    write_model(&mut writer, VISUAL_MODEL_ID, visual.name, false)?;
    write_material(&mut writer)?;
    write_geometry(
        &mut writer,
        COLLIDER_GEOMETRY_ID,
        collider.name,
        &collider,
        false,
    )?;
    write_model(&mut writer, COLLIDER_MODEL_ID, collider.name, true)?;
    writeln!(writer, "}}").map_err(io_error)?;

    writeln!(writer, "Connections: {{").map_err(io_error)?;
    writeln!(
        writer,
        "    C: \"OO\",{VISUAL_GEOMETRY_ID},{VISUAL_MODEL_ID}"
    )
    .map_err(io_error)?;
    writeln!(writer, "    C: \"OO\",{VISUAL_MODEL_ID},0").map_err(io_error)?;
    writeln!(
        writer,
        "    C: \"OO\",{VISUAL_MATERIAL_ID},{VISUAL_MODEL_ID}"
    )
    .map_err(io_error)?;
    writeln!(
        writer,
        "    C: \"OO\",{COLLIDER_GEOMETRY_ID},{COLLIDER_MODEL_ID}"
    )
    .map_err(io_error)?;
    writeln!(writer, "    C: \"OO\",{COLLIDER_MODEL_ID},0").map_err(io_error)?;
    writeln!(writer, "}}").map_err(io_error)?;
    writeln!(writer, "Takes: {{\n    Current: \"\"\n}}").map_err(io_error)?;
    writer
        .flush()
        .map_err(|error| format!("failed to flush native FBX: {error}"))?;
    validate_written_fbx(path, visual.vertices.len(), collider.vertices.len())
}

fn validate_mesh(mesh: &FbxMesh<'_>) -> Result<(), String> {
    if mesh.vertices.is_empty() {
        return Err(format!("FBX mesh {} has no vertices", mesh.name));
    }
    if mesh.triangles.is_empty() {
        return Err(format!("FBX mesh {} has no triangles", mesh.name));
    }
    for (face_index, face) in mesh.triangles.iter().enumerate() {
        if face
            .iter()
            .any(|index| *index as usize >= mesh.vertices.len())
        {
            return Err(format!(
                "FBX mesh {} face {} references a missing vertex",
                mesh.name, face_index
            ));
        }
    }
    Ok(())
}

