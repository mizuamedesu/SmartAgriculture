fn write_geometry(
    writer: &mut impl Write,
    id: i64,
    name: &str,
    mesh: &FbxMesh<'_>,
    include_colors: bool,
) -> Result<(), String> {
    writeln!(
        writer,
        "    Geometry: {id}, \"Geometry::{name}_mesh\", \"Mesh\" {{"
    )
    .map_err(io_error)?;
    writeln!(writer, "        GeometryVersion: 124").map_err(io_error)?;

    let vertex_value_count = mesh.vertices.len() * 3;
    writeln!(writer, "        Vertices: *{vertex_value_count} {{").map_err(io_error)?;
    write_f64_array(
        writer,
        mesh.vertices
            .iter()
            .flat_map(|vertex| vertex.position.into_iter()),
    )?;
    writeln!(writer, "        }}").map_err(io_error)?;

    let index_value_count = mesh.triangles.len() * 3;
    writeln!(
        writer,
        "        PolygonVertexIndex: *{index_value_count} {{"
    )
    .map_err(io_error)?;
    write_i64_array(
        writer,
        mesh.triangles
            .iter()
            .flat_map(|face| [face[0] as i64, face[1] as i64, -(face[2] as i64) - 1]),
    )?;
    writeln!(writer, "        }}").map_err(io_error)?;

    if include_colors {
        writeln!(writer, "        LayerElementColor: 0 {{").map_err(io_error)?;
        writeln!(writer, "            Version: 101").map_err(io_error)?;
        writeln!(writer, "            Name: \"scan_vertex_color\"").map_err(io_error)?;
        writeln!(writer, "            MappingInformationType: \"ByVertice\"").map_err(io_error)?;
        writeln!(writer, "            ReferenceInformationType: \"Direct\"").map_err(io_error)?;
        let color_value_count = mesh.vertices.len() * 4;
        writeln!(writer, "            Colors: *{color_value_count} {{").map_err(io_error)?;
        write_f64_array(
            writer,
            mesh.vertices
                .iter()
                .flat_map(|vertex| vertex.color.into_iter()),
        )?;
        writeln!(writer, "            }}").map_err(io_error)?;
        writeln!(writer, "        }}").map_err(io_error)?;
    }

    writeln!(writer, "        LayerElementMaterial: 0 {{").map_err(io_error)?;
    writeln!(writer, "            Version: 101").map_err(io_error)?;
    writeln!(writer, "            MappingInformationType: \"AllSame\"").map_err(io_error)?;
    writeln!(
        writer,
        "            ReferenceInformationType: \"IndexToDirect\""
    )
    .map_err(io_error)?;
    writeln!(
        writer,
        "            Materials: *1 {{\n                a: 0\n            }}"
    )
    .map_err(io_error)?;
    writeln!(writer, "        }}").map_err(io_error)?;
    writeln!(writer, "        Layer: 0 {{").map_err(io_error)?;
    writeln!(writer, "            Version: 100").map_err(io_error)?;
    if include_colors {
        writeln!(
            writer,
            "            LayerElement:  {{\n                Type: \"LayerElementColor\"\n                TypedIndex: 0\n            }}"
        )
        .map_err(io_error)?;
    }
    writeln!(
        writer,
        "            LayerElement:  {{\n                Type: \"LayerElementMaterial\"\n                TypedIndex: 0\n            }}"
    )
    .map_err(io_error)?;
    writeln!(writer, "        }}").map_err(io_error)?;
    writeln!(writer, "    }}").map_err(io_error)
}

