fn write_f64_array(
    writer: &mut impl Write,
    values: impl IntoIterator<Item = f64>,
) -> Result<(), String> {
    write!(writer, "            a: ").map_err(io_error)?;
    for (index, value) in values.into_iter().enumerate() {
        if index > 0 {
            write!(writer, ",").map_err(io_error)?;
        }
        if index > 0 && index % 24 == 0 {
            write!(writer, "\n               ").map_err(io_error)?;
        }
        write!(writer, "{value:.9}").map_err(io_error)?;
    }
    writeln!(writer).map_err(io_error)
}

fn write_i64_array(
    writer: &mut impl Write,
    values: impl IntoIterator<Item = i64>,
) -> Result<(), String> {
    write!(writer, "            a: ").map_err(io_error)?;
    for (index, value) in values.into_iter().enumerate() {
        if index > 0 {
            write!(writer, ",").map_err(io_error)?;
        }
        if index > 0 && index % 36 == 0 {
            write!(writer, "\n               ").map_err(io_error)?;
        }
        write!(writer, "{value}").map_err(io_error)?;
    }
    writeln!(writer).map_err(io_error)
}

fn validate_written_fbx(
    path: &Path,
    visual_vertex_count: usize,
    collider_vertex_count: usize,
) -> Result<(), String> {
    let metadata = fs::metadata(path)
        .map_err(|error| format!("failed to stat native FBX {}: {error}", path.display()))?;
    if metadata.len() < 512 {
        return Err("native FBX output is unexpectedly small".to_string());
    }
    let data = fs::read_to_string(path)
        .map_err(|error| format!("failed to validate native FBX: {error}"))?;
    for required in [
        "; FBX 7.4.0 project file",
        "FBXVersion: 7400",
        "Model::scan_surface",
        "Model::UCX_scan_surface_00",
        "Connections:",
    ] {
        if !data.contains(required) {
            return Err(format!("native FBX validation failed: missing {required}"));
        }
    }
    let visual_values = visual_vertex_count * 3;
    let collider_values = collider_vertex_count * 3;
    if data.matches(&format!("Vertices: *{visual_values}")).count() == 0
        || data
            .matches(&format!("Vertices: *{collider_values}"))
            .count()
            == 0
    {
        return Err("native FBX validation failed: vertex array count mismatch".to_string());
    }
    Ok(())
}

fn io_error(error: std::io::Error) -> String {
    format!("native FBX write failed: {error}")
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::{
        process::Command,
        time::{SystemTime, UNIX_EPOCH},
    };

    #[test]
    fn native_fbx_round_trips_through_assimp_when_available() {
        let vertices = [
            FbxVertex {
                position: [-0.5, 0.0, 0.0],
                color: [1.0, 0.0, 0.0, 1.0],
            },
            FbxVertex {
                position: [0.5, 0.0, 0.0],
                color: [0.0, 1.0, 0.0, 1.0],
            },
            FbxVertex {
                position: [0.0, 1.0, 0.0],
                color: [0.0, 0.0, 1.0, 1.0],
            },
        ];
        let triangles = [[0, 1, 2]];
        let stamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("clock before unix epoch")
            .as_nanos();
        let path = std::env::temp_dir().join(format!(
            "agriscan-native-fbx-{}-{stamp}.fbx",
            std::process::id()
        ));

        write_fbx(
            &path,
            FbxMesh {
                name: "scan_surface",
                vertices: &vertices,
                triangles: &triangles,
            },
            FbxMesh {
                name: "UCX_scan_surface_00",
                vertices: &vertices,
                triangles: &triangles,
            },
        )
        .expect("native FBX export");

        let contents = fs::read_to_string(&path).expect("read native FBX");
        assert!(contents.contains("LayerElementColor"));
        assert!(contents.contains("PolygonVertexIndex: *3"));

        if let Ok(output) = Command::new("assimp").arg("info").arg(&path).output() {
            assert!(
                output.status.success(),
                "Assimp rejected native FBX:\n{}{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
            let report = String::from_utf8_lossy(&output.stdout);
            assert!(
                report
                    .lines()
                    .any(|line| line.starts_with("Meshes:") && line.ends_with('2')),
                "{report}"
            );
        }

        let _ = fs::remove_file(path);
    }
}
